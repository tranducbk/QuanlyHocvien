const TRAINING_SYSTEM_CODES = Object.freeze({
  HE_1: 'HE_1',
  HE_3: 'HE_3',
  HE_4: 'HE_4',
  HE_5: 'HE_5',
  HE_7: 'HE_7',
});

const ENROLLMENT_MODES = Object.freeze({
  COHORT: 'COHORT',
  INDIVIDUAL: 'INDIVIDUAL',
});

const ENROLLMENT_MODE_BY_SYSTEM = Object.freeze({
  [TRAINING_SYSTEM_CODES.HE_1]: ENROLLMENT_MODES.COHORT,
  [TRAINING_SYSTEM_CODES.HE_3]: ENROLLMENT_MODES.COHORT,
  [TRAINING_SYSTEM_CODES.HE_4]: ENROLLMENT_MODES.COHORT,
  [TRAINING_SYSTEM_CODES.HE_5]: ENROLLMENT_MODES.INDIVIDUAL,
  [TRAINING_SYSTEM_CODES.HE_7]: ENROLLMENT_MODES.COHORT,
});

const getEnrollmentMode = (systemCode) => ENROLLMENT_MODE_BY_SYSTEM[systemCode] || null;

module.exports = { TRAINING_SYSTEM_CODES, ENROLLMENT_MODES, getEnrollmentMode };
